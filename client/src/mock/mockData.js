let taskCounter = 1040;
const nextTaskId = () => {
  taskCounter += 1;
  return `t_${taskCounter}`;
};

const buildTask = ({
  title,
  projectId,
  status,
  priority,
  assigneeId,
  creatorId,
  description,
  deadline, // days from now (positive = future, negative = past)
  commentCount = 0,
  fileCount = 0,
  reviewCount = 0,
}) => {
  const id = nextTaskId();
  const createdAt = DAYS(30);
  const updatedAt = HOURS(Math.random() * 36);
  return {
    id,
    code: `#${1040 + parseInt(id.split('_')[1], 10) - 1040}`,
    title,
    description: description || taskDescs[Math.floor(Math.random() * taskDescs.length)],
    projectId,
    status,
    priority,
    assigneeId,
    creatorId,
    deadline: deadline != null
      ? (deadline >= 0 ? FUTURE_DAYS(deadline) : DAYS(-deadline))
      : null,
    estimatedHours: Math.floor(Math.random() * 12) + 2,
    actualHours: Math.floor(Math.random() * 14),
    tags: ['Frontend', 'Backend', 'API', 'UI', 'DevOps'][Math.floor(Math.random() * 5)],
    createdAt,
    updatedAt,
    completedAt: status === TASK_STATUS.COMPLETED ? HOURS(Math.random() * 48) : null,
    commentCount,
    fileCount,
    reviewCount,
    acceptanceCriteria: ACC_CRITERIA,
    dependencies: [],
  };
};

